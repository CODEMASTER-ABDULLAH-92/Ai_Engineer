# ============================================================
# INSTANCE VARIABLES
# ============================================================

# Instance variables are variables that belong to a specific object.
#
# They are usually created using `self`.
#
# Example:
#
# class Student:
#
#     def __init__(self, name, age):
#         self.name = name
#         self.age = age
#
# `self.name` and `self.age` are instance variables.
#
# Each object can have different values:
#
# student1.name = "Ali"
# student2.name = "Ahmed"
#
# Easy rule:
#
# self.variable → Instance Variable
#
# Instance variable = Data belonging to a particular object.