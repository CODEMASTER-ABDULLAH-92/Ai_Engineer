# ============================================================
# CLASS VARIABLES
# ============================================================

# Class variables belong to the class.
#
# They are defined inside the class but outside methods.
#
# They are shared by all objects.
#
# Example:
#
# class Student:
#     school = "GCUF"       # Class variable
#
#     def __init__(self, name):
#         self.name = name  # Instance variable
#
#
# IMPORTANT:
# Class variable → shared by all objects
# Instance variable → different for each object
#
# Access class variable:
# Student.school
# student1.school
#
#
# HINT:
# variable inside class, outside methods → Class Variable
# self.variable → Instance Variable
#
# Easy memory:
# Class = Shared
# Object = Individual